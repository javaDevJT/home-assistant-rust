//! Provider-owned entity metadata updates.
//!
//! Entity providers report the original values they expose. User overrides
//! (`name`, `icon`, and `device_class`) live in the registry entry separately
//! and are never changed by a provider refresh.

use chrono::Utc;
use serde_json::Value;
use std::collections::HashSet;

use crate::{
    EntityEntry, EntityRegistration, Registries, RegistryEvent, Result, entity_change_values,
    entity_id_available, entity_identity_matches, validate_registration,
};

/// Original entity metadata supplied by its provider.
///
/// User-facing overrides are intentionally absent. A provider may update this
/// value repeatedly without replacing a user's name, icon, device-class
/// override, disabled state, or chosen entity ID.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct ProviderEntityInfo {
    /// Provider's original entity name.
    pub original_name: Option<String>,
    /// Provider's original icon.
    pub original_icon: Option<String>,
    /// Provider's original device class.
    pub original_device_class: Option<String>,
    /// Provider's suggested object ID for a newly created entry.
    pub suggested_object_id: Option<String>,
    /// Entity category supplied by the provider.
    pub entity_category: Option<String>,
    /// Whether the entity name is combined with its device name.
    pub has_entity_name: bool,
    /// Unit exposed by the provider.
    pub unit_of_measurement: Option<String>,
    /// Provider-supported features.
    pub supported_features: u64,
    /// Translation key supplied by the provider.
    pub translation_key: Option<String>,
    /// Capability attributes supplied by the provider.
    pub capabilities: Option<Value>,
}

/// A registry identity together with its current provider-owned metadata.
#[derive(Clone, Debug, PartialEq)]
pub struct ProviderEntityRegistration {
    /// Stable registry identity and non-provider links.
    pub registration: EntityRegistration,
    /// Current provider-owned metadata.
    pub info: ProviderEntityInfo,
}

impl ProviderEntityRegistration {
    /// Construct a provider registration from the registry identity and
    /// provider-owned metadata.
    #[must_use]
    pub fn new(registration: EntityRegistration, info: ProviderEntityInfo) -> Self {
        Self { registration, info }
    }
}

impl Registries {
    /// Get or create provider entities and refresh their original metadata in a
    /// single registry transaction.
    ///
    /// The batch is validated before any entry is changed. Duplicate provider
    /// identities are rejected. Existing entries retain their current entity
    /// ID, user overrides, aliases, and disabled/hidden settings. No aliases
    /// are generated by this API.
    pub fn get_or_create_provider_entities(
        &self,
        registrations: Vec<ProviderEntityRegistration>,
    ) -> Result<Vec<EntityEntry>> {
        self.get_or_create_provider_entities_reserving(registrations, &HashSet::new())
    }

    /// Get or create provider entities while reserving IDs allocated for
    /// unregistered entities in the same provider batch.
    pub fn get_or_create_provider_entities_reserving(
        &self,
        registrations: Vec<ProviderEntityRegistration>,
        reserved_entity_ids: &HashSet<String>,
    ) -> Result<Vec<EntityEntry>> {
        for item in &registrations {
            validate_registration(&item.registration)?;
        }

        let mut identities = std::collections::HashSet::new();
        for item in &registrations {
            let registration = &item.registration;
            if !identities.insert((
                registration.domain.as_str(),
                registration.platform.as_str(),
                registration.unique_id.as_str(),
            )) {
                return Err(crate::invalid(format!(
                    "duplicate provider entity identity {} / {} / {}",
                    registration.domain, registration.platform, registration.unique_id
                )));
            }
        }

        self.transact(|data| {
            if let Some(entry) = data.entities.iter().find(|entry| {
                reserved_entity_ids.contains(&entry.entity_id)
                    && registrations
                        .iter()
                        .any(|item| entity_identity_matches(entry, &item.registration))
            }) {
                return Err(crate::invalid(format!(
                    "registered entity ID {} collides with a provider-generated ID",
                    entry.entity_id
                )));
            }
            let mut result = Vec::with_capacity(registrations.len());
            let mut events = Vec::new();

            for item in registrations {
                let mut registration = item.registration;
                apply_provider_info_to_registration(&mut registration, &item.info);

                if let Some(index) = data
                    .entities
                    .iter()
                    .position(|entry| entity_identity_matches(entry, &registration))
                {
                    let old = data.entities[index].clone();
                    if reserved_entity_ids.contains(&old.entity_id) {
                        return Err(crate::invalid(format!(
                            "registered entity ID {} collides with a provider-generated ID",
                            old.entity_id
                        )));
                    }
                    let mut new = old.clone();
                    new.device_id = registration.device_id.clone();
                    new.area_id = registration.area_id.clone().or(new.area_id);
                    new.config_entry_id = registration.config_entry_id.clone();
                    new.config_subentry_id = registration.config_subentry_id.clone();
                    apply_provider_info_to_entry(&mut new, &item.info);

                    if new != old {
                        new.modified_at = Utc::now();
                        let changes = entity_change_values(&old, &new);
                        events.push(RegistryEvent::changed(
                            "entity_registry_updated",
                            "entity_id",
                            &new.entity_id,
                            changes,
                        ));
                        data.entities[index] = new.clone();
                    }
                    result.push(new);
                    continue;
                }

                if let Some(index) = data
                    .deleted_entities
                    .iter()
                    .position(|entry| entity_identity_matches(entry, &registration))
                {
                    let mut restored = data.deleted_entities.remove(index);
                    if !entity_id_available(data, &restored.entity_id, &self.inner.runtime)
                        || reserved_entity_ids.contains(&restored.entity_id)
                    {
                        restored.entity_id = generate_provider_entity_id(
                            data,
                            &registration,
                            &self.inner.runtime,
                            reserved_entity_ids,
                        );
                        restored.id = crate::new_hex_id();
                    }
                    restored.device_id = registration.device_id.clone();
                    restored.area_id = registration.area_id.clone().or(restored.area_id);
                    restored.config_entry_id = registration.config_entry_id.clone();
                    restored.config_subentry_id = registration.config_subentry_id.clone();
                    apply_provider_info_to_entry(&mut restored, &item.info);
                    restored.modified_at = Utc::now();
                    data.entities.push(restored.clone());
                    events.push(RegistryEvent::item(
                        "entity_registry_updated",
                        "create",
                        "entity_id",
                        &restored.entity_id,
                    ));
                    result.push(restored);
                    continue;
                }

                let now = Utc::now();
                let mut entry = EntityEntry {
                    id: crate::new_hex_id(),
                    entity_id: generate_provider_entity_id(
                        data,
                        &registration,
                        &self.inner.runtime,
                        reserved_entity_ids,
                    ),
                    domain: registration.domain.clone(),
                    platform: registration.platform.clone(),
                    unique_id: registration.unique_id.clone(),
                    previous_unique_id: None,
                    aliases: Vec::new(),
                    area_id: registration.area_id.clone(),
                    categories: Default::default(),
                    capabilities: None,
                    config_entry_id: registration.config_entry_id.clone(),
                    config_subentry_id: registration.config_subentry_id.clone(),
                    created_at: now,
                    device_class: None,
                    device_id: registration.device_id.clone(),
                    disabled_by: registration.disabled_by.clone(),
                    entity_category: registration.entity_category.clone(),
                    hidden_by: None,
                    icon: None,
                    labels: registration.labels.clone(),
                    modified_at: now,
                    name: None,
                    options: Default::default(),
                    original_device_class: None,
                    original_icon: None,
                    original_name: None,
                    suggested_object_id: registration.suggested_object_id.clone(),
                    supported_features: registration.supported_features,
                    translation_key: registration.translation_key.clone(),
                    unit_of_measurement: registration.unit_of_measurement.clone(),
                    has_entity_name: registration.has_entity_name,
                };
                apply_provider_info_to_entry(&mut entry, &item.info);
                data.entities.push(entry.clone());
                events.push(RegistryEvent::item(
                    "entity_registry_updated",
                    "create",
                    "entity_id",
                    &entry.entity_id,
                ));
                result.push(entry);
            }

            Ok((result, events))
        })
    }

    /// Refresh provider-owned metadata for the entity currently using
    /// `entity_id` without changing its identity or user settings.
    pub fn update_provider_entity_info(
        &self,
        entity_id: &str,
        info: ProviderEntityInfo,
    ) -> Result<EntityEntry> {
        self.transact(|data| {
            let index = data
                .entities
                .iter()
                .position(|entry| entry.entity_id == entity_id)
                .ok_or_else(|| crate::Error::NotFound(format!("entity {entity_id}")))?;
            let old = data.entities[index].clone();
            let mut new = old.clone();
            apply_provider_info_to_entry(&mut new, &info);
            if new == old {
                return Ok((old, Vec::new()));
            }
            new.modified_at = Utc::now();
            let changes = entity_change_values(&old, &new);
            data.entities[index] = new.clone();
            Ok((
                new.clone(),
                vec![RegistryEvent::changed(
                    "entity_registry_updated",
                    "entity_id",
                    &new.entity_id,
                    changes,
                )],
            ))
        })
    }

    /// Look up a registered provider entity by its stable registry entry ID.
    pub fn provider_entity(&self, registry_id: &str) -> Option<EntityEntry> {
        self.inner
            .data
            .read()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .entities
            .iter()
            .find(|entry| entry.id == registry_id)
            .cloned()
    }

    /// IDs held by current or deleted entity registry entries.
    pub fn provider_reserved_entity_ids(&self) -> HashSet<String> {
        let data = self
            .inner
            .data
            .read()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        data.entities
            .iter()
            .chain(data.deleted_entities.iter())
            .map(|entry| entry.entity_id.clone())
            .collect()
    }
}

fn generate_provider_entity_id(
    data: &crate::RegistryData,
    registration: &EntityRegistration,
    runtime: &crate::Runtime,
    reserved_entity_ids: &HashSet<String>,
) -> String {
    let fallback = format!("{}_{}", registration.platform, registration.unique_id);
    let base = registration
        .name
        .as_deref()
        .or(registration.suggested_object_id.as_deref())
        .or(registration.original_name.as_deref())
        .unwrap_or(&fallback);
    let object = crate::slugify(base);
    let base_id = format!("{}.{}", registration.domain, object);
    if entity_id_available(data, &base_id, runtime) && !reserved_entity_ids.contains(&base_id) {
        return base_id;
    }
    let mut suffix = 2;
    loop {
        let candidate = format!("{}.{}_{}", registration.domain, object, suffix);
        if entity_id_available(data, &candidate, runtime)
            && !reserved_entity_ids.contains(&candidate)
        {
            return candidate;
        }
        suffix += 1;
    }
}

fn apply_provider_info_to_registration(
    registration: &mut EntityRegistration,
    info: &ProviderEntityInfo,
) {
    // These fields are user settings in the registry representation. Provider
    // values are stored only in their `original_*` counterparts.
    registration.name = None;
    registration.icon = None;
    registration.device_class = None;
    registration.original_name = info.original_name.clone();
    registration.original_icon = info.original_icon.clone();
    registration.original_device_class = info.original_device_class.clone();
    registration.suggested_object_id = info
        .suggested_object_id
        .clone()
        .or(registration.suggested_object_id.clone());
    registration.entity_category = info
        .entity_category
        .clone()
        .or(registration.entity_category.clone());
    registration.has_entity_name = info.has_entity_name;
    registration.unit_of_measurement = info
        .unit_of_measurement
        .clone()
        .or(registration.unit_of_measurement.clone());
    registration.supported_features = info.supported_features;
    registration.translation_key = info
        .translation_key
        .clone()
        .or(registration.translation_key.clone());
}

fn apply_provider_info_to_entry(entry: &mut EntityEntry, info: &ProviderEntityInfo) {
    entry.original_name = info.original_name.clone();
    entry.original_icon = info.original_icon.clone();
    entry.original_device_class = info.original_device_class.clone();
    if info.suggested_object_id.is_some() {
        entry.suggested_object_id = info.suggested_object_id.clone();
    }
    entry.entity_category = info.entity_category.clone();
    entry.has_entity_name = info.has_entity_name;
    entry.unit_of_measurement = info.unit_of_measurement.clone();
    entry.supported_features = info.supported_features;
    entry.translation_key = info.translation_key.clone();
    entry.capabilities = info.capabilities.clone();
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{EntityUpdate, Registries};
    use hass_core::{MemoryStore, Runtime};
    use serde_json::json;
    use std::sync::Arc;

    fn registry() -> Registries {
        let runtime = Runtime::new(Arc::new(MemoryStore::default())).unwrap();
        Registries::new(runtime).unwrap()
    }

    fn provider_registration(name: &str) -> ProviderEntityRegistration {
        let mut registration = EntityRegistration::new("sensor", "fixture", "reading");
        registration.suggested_object_id = Some("reading".into());
        ProviderEntityRegistration::new(
            registration,
            ProviderEntityInfo {
                original_name: Some(name.into()),
                original_icon: Some("mdi:thermometer".into()),
                original_device_class: Some("temperature".into()),
                unit_of_measurement: Some("°C".into()),
                suggested_object_id: Some("reading".into()),
                ..ProviderEntityInfo::default()
            },
        )
    }

    #[test]
    fn provider_refresh_keeps_user_overrides_and_entity_id() {
        let registries = registry();
        let first = registries
            .get_or_create_provider_entities(vec![provider_registration("Room")])
            .unwrap()
            .remove(0);
        let overridden = registries
            .update_entity(
                &first.entity_id,
                EntityUpdate {
                    name: Some(Some("Custom name".into())),
                    icon: Some(Some("mdi:home".into())),
                    device_class: Some(Some("humidity".into())),
                    new_entity_id: Some("sensor.living_room".into()),
                    ..EntityUpdate::default()
                },
            )
            .unwrap();

        let refreshed = registries
            .get_or_create_provider_entities(vec![provider_registration("Updated room")])
            .unwrap()
            .remove(0);

        assert_eq!(refreshed.id, first.id);
        assert_eq!(refreshed.entity_id, overridden.entity_id);
        assert_eq!(refreshed.name.as_deref(), Some("Custom name"));
        assert_eq!(refreshed.icon.as_deref(), Some("mdi:home"));
        assert_eq!(refreshed.device_class.as_deref(), Some("humidity"));
        assert_eq!(refreshed.original_name.as_deref(), Some("Updated room"));
        assert_eq!(refreshed.original_icon.as_deref(), Some("mdi:thermometer"));
        assert_eq!(
            refreshed.original_device_class.as_deref(),
            Some("temperature")
        );
    }

    #[test]
    fn provider_batch_preflights_duplicate_identity_without_creating_aliases() {
        let registries = registry();
        let error = registries
            .get_or_create_provider_entities(vec![
                provider_registration("One"),
                provider_registration("Two"),
            ])
            .unwrap_err();
        assert!(
            error
                .to_string()
                .contains("duplicate provider entity identity")
        );
        assert!(registries.entities().is_empty());
    }

    #[test]
    fn deleted_identity_reuses_registry_id_when_available() {
        let registries = registry();
        let first = registries
            .get_or_create_provider_entities(vec![provider_registration("Room")])
            .unwrap()
            .remove(0);
        registries.remove_entity(&first.entity_id).unwrap();
        let restored = registries
            .get_or_create_provider_entities(vec![provider_registration("Room renamed")])
            .unwrap()
            .remove(0);
        assert_eq!(restored.id, first.id);
        assert_eq!(restored.entity_id, first.entity_id);
        assert_eq!(restored.original_name.as_deref(), Some("Room renamed"));
        assert!(restored.aliases.is_empty());
    }

    #[test]
    fn provider_capability_refresh_is_persisted() {
        let registries = registry();
        let registration = ProviderEntityRegistration::new(
            EntityRegistration::new("sensor", "fixture", "reading"),
            ProviderEntityInfo {
                capabilities: Some(json!({"precision": 2})),
                ..ProviderEntityInfo::default()
            },
        );
        let entry = registries
            .get_or_create_provider_entities(vec![registration])
            .unwrap()
            .remove(0);
        assert_eq!(entry.capabilities, Some(json!({"precision": 2})));
        assert_eq!(registries.provider_entity(&entry.id), Some(entry));
    }
}
